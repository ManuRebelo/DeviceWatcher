@app.route('/device/ap/<mac>', methods=['DELETE'])
def delete_ap_route(mac: str):
    """Delete an access point (and its BSSID group) by MAC address.

    @param mac  URL-encoded BSSID of the AP.
    @return     204 on success; 400 for invalid MAC; 404 if not found; 503 if not ready.
    """
    mac = mac.lower()
    if db_manager is None:
        return jsonify({'error': 'initialising'}), 503
    err = _validate_mac(mac)
    if err:
        return err
    if not db_manager.fetch_ap_by_id(mac):
        return jsonify({'error': 'not found'}), 404
    db_manager.delete_ap(mac)
    return '', 204



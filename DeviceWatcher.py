@app.before_request
def _check_auth():
    """Enforce Bearer-token authentication when ``_AUTH_TOKEN`` is configured.

    Static assets are always public.  The ``/live/packets`` SSE endpoint also
    accepts the token as a ``?token=`` query parameter because EventSource
    cannot set custom request headers.

    @return  401 JSON response on failure, or ``None`` to allow the request.
    """
    if _AUTH_TOKEN is None:
        return None
    # Static assets and Doxygen documentation pages are always public.
    if request.endpoint in ('static', 'docs_index', 'docs_static'):
        return None
    header    = request.headers.get('Authorization', '')
    presented = header[7:] if header.startswith('Bearer ') else ''
    if not presented:
        presented = request.args.get('token', '')
    if not presented or not secrets.compare_digest(presented, _AUTH_TOKEN):
        return jsonify({'error': 'unauthorized'}), 401
    return None



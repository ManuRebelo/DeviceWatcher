# ------------------------------------------------------------------ channel hopper control

@app.route('/system/channel_hopper', methods=['GET', 'POST'])
def system_channel_hopper():
    """GET current hopping state or POST a pause/resume action.

    POST body (JSON): ``{"action": "pause"|"resume", "channel": int}``

    When pausing, an optional *channel* value locks the interface to that
    channel using ``iw``.

    @return  JSON ``{"hopping": bool, "current_channel": int}``; 503 if Wi-Fi
             monitor is not active.
    """
    if wifi_monitor is None:
        return jsonify({'error': 'Wi-Fi monitor not active'}), 503

    if request.method == 'POST':
        body   = request.get_json()
        action = body.get('action')
        if action == 'pause':
            wifi_monitor.hopping_paused = True
            ch = body.get('channel')
            if ch and wifi_monitor.interface:
                subprocess.run(
                    ["iw", "dev", wifi_monitor.interface, "set", "channel", str(ch)],
                    stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                )
                wifi_monitor.current_channel = int(ch)
        elif action == 'resume':
            wifi_monitor.hopping_paused = False

    return jsonify({
        'hopping':         not wifi_monitor.hopping_paused,
        'current_channel': wifi_monitor.current_channel,
    })


# ------------------------------------------------------------------ SSE helpers

def _sse_generator(q: queue.Queue):
    """Yield SSE-formatted lines from *q* with keep-alive pings every 15 seconds.

    @param q  Queue pre-populated by a monitor's listener registration.
    @return   Generator of SSE text lines (``data: …\\n\\n`` or ``: ping\\n\\n``).
    """
    try:
        yield ': connected\n\n'
        while True:
            try:
                evt = q.get(timeout=15)
                yield f'data: {json.dumps(evt)}\n\n'
            except queue.Empty:
                yield ': ping\n\n'
    except GeneratorExit:
        pass


def _sse_response(monitor, register_fn, unregister_fn, monitor_name: str):
    """Build an SSE :class:`~flask.Response` for a given monitor.

    @param monitor        Monitor instance (checked for ``None``).
    @param register_fn    Callable to register a listener queue on the monitor.
    @param unregister_fn  Callable to remove the listener queue when the client
                          disconnects.
    @param monitor_name   Human-readable name used in the 503 error message.
    @return               SSE :class:`~flask.Response`, or 503 JSON.
    """
    if monitor is None:
        return jsonify({'error': f'{monitor_name} monitor not active'}), 503

    q: queue.Queue = queue.Queue(maxsize=500)
    register_fn(q)

    @stream_with_context
    def generate():
        try:
            yield from _sse_generator(q)
        finally:
            unregister_fn(q)

    return Response(
        generate(),
        mimetype='text/event-stream',
        headers={'Cache-Control': 'no-cache', 'X-Accel-Buffering': 'no'},
    )



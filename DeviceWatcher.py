@app.route('/system/settings', methods=['GET', 'POST'])
def system_settings_route():
    """GET or POST Wi-Fi monitor runtime settings.

    POST body (JSON): ``{"dwell_time": float, "band_filter": str}``

    Valid *dwell_time* range: [0.05, 0.5] seconds.
    Valid *band_filter* values: ``"all"``, ``"2.4"``, ``"5"``, ``"6"``.

    @return  JSON ``{"wifi": {"dwell_time": float, "band_filter": str}}``.
    """
    if request.method == 'POST':
        body = request.get_json(silent=True) or {}
        if wifi_monitor is not None:
            if 'dwell_time' in body:
                val = float(body['dwell_time'])
                if 0.05 <= val <= 0.5:
                    wifi_monitor.dwell_time = round(val, 3)
            if 'band_filter' in body and body['band_filter'] in ('all', '2.4', '5', '6'):
                wifi_monitor.band_filter = body['band_filter']
    return jsonify({
        'wifi': {
            'dwell_time':  wifi_monitor.dwell_time  if wifi_monitor else 0.15,
            'band_filter': wifi_monitor.band_filter if wifi_monitor else 'all',
        }
    })


@app.route('/system/status')
def system_status():
    """Return the current operational status of each monitor subsystem.

    Wi-Fi active is determined by whether the channel hopper is still running.
    BT/BLE active means scanning with zero consecutive errors.

    @return  JSON ``{"wifi": {...}, "bt": {...}, "ble": {...}}``.
    """
    wifi_configured = wifi_monitor is not None
    wifi_active     = wifi_configured and not wifi_monitor._stop_hopping.is_set()

    bt_configured = bluetooth_monitor is not None
    bt_scanning   = bt_configured and bluetooth_monitor.scanning
    bt_active     = bt_scanning and bluetooth_monitor._error_count == 0
    bt_error      = bt_scanning and bluetooth_monitor._error_count > 0

    ble_configured = ble_monitor is not None
    ble_scanning   = ble_configured and ble_monitor.scanning
    ble_active     = ble_scanning and ble_monitor._error_count == 0
    ble_error      = ble_scanning and ble_monitor._error_count > 0

    return jsonify({
        'wifi': {
            'interface': wifi_monitor.interface if wifi_configured else None,
            'active':    wifi_active,
            'error':     wifi_configured and not wifi_active,
        },
        'bt': {
            'interface': f"hci{bluetooth_monitor.interface}" if bt_configured else None,
            'active':    bt_active,
            'error':     bt_error,
        },
        'ble': {
            'interface': f"hci{ble_monitor.interface}" if ble_configured else None,
            'active':    ble_active,
            'error':     ble_error,
        },
    })



@app.route('/analytics/clusters/config', methods=['GET', 'POST'])
def analytics_clusters_config():
    """GET or POST the clustering affinity-score threshold.

    POST body (JSON): ``{"threshold": float}``  (must be in [0.05, 0.95])

    @return  JSON ``{"threshold": float}``; 400 on invalid value.
    """
    global _cluster_threshold
    if request.method == 'POST':
        body = request.get_json(silent=True) or {}
        try:
            val = float(body.get('threshold', _cluster_threshold))
            if not (0.05 <= val <= 0.95):
                return jsonify({'error': 'threshold must be between 0.05 and 0.95'}), 400
            _cluster_threshold = round(val, 2)
        except (TypeError, ValueError):
            return jsonify({'error': 'invalid threshold'}), 400
    return jsonify({'threshold': _cluster_threshold})



@app.route('/live/packets')
def live_packets():
    """Server-Sent Events stream of live Wi-Fi packet summaries.

    Accepts ``?token=`` for authentication (EventSource cannot set headers).

    @return  SSE stream; 503 when the Wi-Fi monitor is not active.
    """
    if wifi_monitor is None:
        return jsonify({'error': 'Wi-Fi monitor not active'}), 503

    q: queue.Queue = queue.Queue(maxsize=500)
    wifi_monitor.register_packet_listener(q)

    @stream_with_context
    def generate():
        try:
            yield from _sse_generator(q)
        finally:
            wifi_monitor.unregister_packet_listener(q)

    return Response(
        generate(),
        mimetype='text/event-stream',
        headers={'Cache-Control': 'no-cache', 'X-Accel-Buffering': 'no'},
    )



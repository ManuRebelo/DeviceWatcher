# ------------------------------------------------------------------ entry point

def main():
    """Parse CLI arguments, initialise all subsystems, and start the HTTP server.

    Supported arguments
    -------------------
    ``--wifi IFACE``         Monitor-mode Wi-Fi interface.
    ``--bt N``               Bluetooth Classic HCI index.
    ``--ble N``              BLE HCI index.
    ``--host ADDR``          Bind address (default ``127.0.0.1``).
    ``--port PORT``          HTTP port (default ``5000``).
    ``--auth-token TOKEN``   Bearer token; falls back to ``DEVICEWATCHER_TOKEN`` env var.
    ``--oui-file PATH``      Additional OUI source file.
    ``--enable-vendor-api``  Allow external MAC vendor API lookups.
    """
    global db_manager, wifi_monitor, bluetooth_monitor, ble_monitor
    global analytics_engine, vendor_resolver, _AUTH_TOKEN
    global _EXTERNAL_API_ENABLED, _cluster_threshold

    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s',
    )

    parser = argparse.ArgumentParser(description='DeviceWatcher — network monitoring dashboard')
    parser.add_argument('--wifi',   type=str, help='Wi-Fi monitor-mode interface (e.g. wlan1mon)')
    parser.add_argument('--bt',     type=int, help='Bluetooth Classic HCI index (e.g. 2)')
    parser.add_argument('--ble',    type=int, help='BLE HCI index (e.g. 0)')
    parser.add_argument('--host',   type=str, default='127.0.0.1',
                        help='HTTP bind address. Defaults to 127.0.0.1 (localhost only). '
                             'Use 0.0.0.0 to expose on the LAN — combine with --auth-token.')
    parser.add_argument('--port',   type=int, default=5000, help='HTTP port (default 5000)')
    parser.add_argument('--auth-token', type=str, default=None,
                        help='Require this Bearer token on every request. '
                             'Falls back to the DEVICEWATCHER_TOKEN env var.')
    parser.add_argument('--oui-file', type=str, default=None,
                        help='Path to a Wireshark `manuf` or IEEE-style OUI CSV.')
    parser.add_argument('--enable-vendor-api', action='store_true',
                        help='Allow falling back to public macvendors.com / macvendorlookup.com '
                             'for unknown MACs. Off by default (sends every observed MAC to a '
                             'third party).')
    args = parser.parse_args()

    _AUTH_TOKEN           = args.auth_token or os.environ.get('DEVICEWATCHER_TOKEN') or None
    _EXTERNAL_API_ENABLED = args.enable_vendor_api
    if args.host != '127.0.0.1' and not _AUTH_TOKEN:
        logging.warning(
            "Listening on %s without --auth-token: anyone on the network can read "
            "the dashboard and delete devices.", args.host,
        )

    db_manager       = DatabaseManager()
    analytics_engine = AnalyticsEngine(db_manager)
    vendor_resolver  = VendorResolver(
        oui_file=args.oui_file,
        allow_external_api=args.enable_vendor_api,
    )
    known_devices    = load_known_devices()

    wifi_monitor      = WiFiMonitor(db_manager, vendor_resolver, known_devices) if args.wifi else None
    bluetooth_monitor = (
        BluetoothClassicMonitor(args.bt, db_manager, vendor_resolver, known_devices)
        if args.bt is not None else None
    )
    ble_monitor = (
        BLEMonitor(args.ble, db_manager, vendor_resolver, known_devices)
        if args.ble is not None else None
    )

    if wifi_monitor:
        Thread(target=wifi_monitor.start_sniffing, args=(args.wifi,), daemon=True).start()
    if bluetooth_monitor:
        Thread(target=bluetooth_monitor.start_scan, daemon=True).start()
    if ble_monitor:
        Thread(target=ble_monitor.start_scan, daemon=True).start()

    def _shutdown(*_):
        logging.info("Shutting down DeviceWatcher…")
        if wifi_monitor:
            try:
                wifi_monitor.stop_sniffing()
            except Exception as exc:
                logging.warning("Error stopping Wi-Fi monitor: %s", exc)
        if bluetooth_monitor:
            try:
                bluetooth_monitor.stop_scan()
            except Exception as exc:
                logging.warning("Error stopping BT monitor: %s", exc)
        if ble_monitor:
            try:
                ble_monitor.stop_scan()
            except Exception as exc:
                logging.warning("Error stopping BLE monitor: %s", exc)
        try:
            db_manager.close()
        except Exception as exc:
            logging.warning("Error closing database: %s", exc)

    # SIGTERM (e.g. systemd stop) doesn't otherwise unblock serve(); install a
    # handler so subprocesses (hcitool) are terminated cleanly.
    signal.signal(signal.SIGTERM, lambda *_: (_shutdown(), os._exit(0)))

    try:
        try:
            from waitress import serve
            logging.info("Serving with waitress on http://%s:%d", args.host, args.port)
            serve(app, host=args.host, port=args.port, threads=8, _quiet=False)
        except ImportError:
            if args.host != '127.0.0.1':
                logging.warning(
                    "waitress not installed; exposing Flask dev server on network is insecure!"
                )
            else:
                logging.warning("waitress not installed; using Flask dev server")
            app.run(host=args.host, port=args.port, debug=False)
    except KeyboardInterrupt:
        pass
    finally:
        _shutdown()


if __name__ == '__main__':
    main()

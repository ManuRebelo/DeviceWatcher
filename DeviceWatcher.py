# ------------------------------------------------------------------ validation

def _validate_mac(mac: str):
    """Validate *mac* against the standard colon-separated hex pattern.

    @param mac  MAC address string to validate.
    @return     400 JSON response when invalid, or ``None`` when valid.
    """
    if not _MAC_RE.match(mac):
        return jsonify({'error': 'invalid MAC'}), 400
    return None


